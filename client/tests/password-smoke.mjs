// A disposable account and synthetic descriptor; no camera or WebAuthn automation.
import assert from 'node:assert/strict'
import {randomBytes} from 'node:crypto'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})})
const username='smoke_'+randomBytes(5).toString('hex'),password=randomBytes(24).toString('hex'),replacement=randomBytes(24).toString('hex')
try{
 const page=await browser.newPage();const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.addInitScript(()=>{
   navigator.credentials.create=()=>{throw new Error('Unexpected passkey prompt')}
   navigator.credentials.get=()=>{throw new Error('Unexpected passkey prompt')}
 })
 await page.goto(process.env.PRIVFACE_URL||'http://localhost:5173')
 await page.getByRole('button',{name:'Register',exact:true}).click()
 await page.getByLabel('Username',{exact:true}).fill(username)
 await page.getByLabel('Password',{exact:true}).fill(password)
 await page.getByLabel('Confirm password',{exact:true}).fill(password)
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Create account & capture face'}).click()
 await page.getByRole('heading',{name:'Set up your face.'}).waitFor()
 await page.getByRole('button',{name:'Enable camera',exact:true}).waitFor()
 assert.equal(await page.getByLabel('Account invitation').count(),0)
 await page.evaluate(async username=>{
   const {encryptTemplate}=await import('/src/template-crypto.ts')
   const {saveEnrollment}=await import('/src/enrollment-store.ts')
   await saveEnrollment(await encryptTemplate(username,'Synthetic',Array.from({length:128},(_,i)=>(i+1)/256)),new AbortController().signal)
 },username)
 await page.getByText('Account security',{exact:true}).click()
 await page.getByRole('button',{name:'Link or refresh saved face enrollment'}).click()
 await page.getByText('Face enrollment linked to your account.',{exact:true}).waitFor()
 const result=await page.evaluate(async()=>{
   const {proveMatch}=await import('/src/proof-client.ts');const {getEnrollment}=await import('/src/enrollment-store.ts')
   const session=await (await fetch('/api/session')).json()
   return proveMatch(session,await getEnrollment(session.account.username),Array.from({length:128},(_,i)=>(i+1)/256),new AbortController().signal)
 })
 assert.equal(result.verified,true)
 await page.getByLabel('Current password',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Generate recovery code',exact:true}).click()
 const code=await page.locator('code').innerText()
 await page.getByRole('button',{name:'Sign out',exact:true}).click()
 await page.getByRole('button',{name:'Log in',exact:true}).first().click()
 await page.getByLabel('Username',{exact:true}).fill(username)
 await page.getByLabel('Password',{exact:true}).fill('wrong password')
 await page.getByRole('button',{name:'Log in',exact:true}).last().click()
 await page.getByRole('alert').filter({hasText:'incorrect'}).waitFor()
 await page.getByLabel('Password',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Log in',exact:true}).last().click()
 await page.getByRole('heading',{name:'You’re signed in.'}).waitFor()
 await page.getByRole('button',{name:'Sign out',exact:true}).click()
 await page.getByText('Forgot your password?',{exact:true}).click()
 await page.getByLabel('Recovery code',{exact:true}).fill(code)
 await page.getByLabel('New password',{exact:true}).fill(replacement)
 await page.getByLabel('Confirm new password',{exact:true}).fill(replacement)
 await page.getByRole('button',{name:'Reset password',exact:true}).click()
 await page.getByRole('heading',{name:'You’re signed in.'}).waitFor()
 const recovered=await page.evaluate(async()=>(await fetch('/api/session')).json())
 assert.equal(recovered.authentication,'password');assert.equal(recovered.enrollment,null)
 assert.deepEqual(errors,[])
 await page.getByText('Account security',{exact:true}).click()
 await page.getByLabel('Current password',{exact:true}).fill(replacement)
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Disable account',exact:true}).click()
 await page.getByText('All sessions ended.',{exact:true}).waitFor()
 console.log('PASS: open password signup, capture-step navigation, binding, real browser proof, incorrect/correct password login, recovery and disablement. No passkey APIs called. Synthetic descriptor only.')
}finally{await browser.close()}
