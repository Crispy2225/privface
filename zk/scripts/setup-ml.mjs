// Independent M2/M3 artifact set. Does not replace legacy descriptor proofs.
import {readFile,writeFile,mkdir,copyFile,access} from 'node:fs/promises'
import {createHash,randomBytes} from 'node:crypto'
import {spawn} from 'node:child_process'
import {fileURLToPath} from 'node:url'
import {resolve} from 'node:path'
import constants from '../node_modules/circomlibjs/src/poseidon_constants.js'
import {validateModel,tagForHash} from '../../client/public/zkml/runtime.mjs'
const root=fileURLToPath(new URL('../',import.meta.url)), out=resolve(root,'artifacts-ml'), pub=resolve(root,'../client/public/zkml')
const hash=b=>createHash('sha256').update(b).digest('hex')
await mkdir(out,{recursive:true}); await mkdir(resolve(root,'generated'),{recursive:true})
try {await access(out+'/manifest.json');throw new Error('M3 setup exists. Use a new artifact directory or explicitly remove it after preserving evidence.')}catch(e){if(e.code!=='ENOENT')throw e}
const modelBytes=await readFile(pub+'/model.json'), m=validateModel(JSON.parse(modelBytes))
const policyBytes=await readFile(pub+'/policy.json'), policy=JSON.parse(policyBytes)
const modelHash=hash(modelBytes)
if(policy.modelSHA256!==modelHash)throw new Error('Policy/model mismatch')
const generated='pragma circom 2.1.6;\n// Generated by setup-ml.mjs; public frozen weights.\n'+
  [['weights1',m.w1],['bias1',m.b1],['weights2',m.w2],['bias2',m.b2]].map(([name,data])=>`function ${name}() { return ${JSON.stringify(data)}; }\n`).join('')+
  `function modelIdentity() { return ${tagForHash(modelHash)}; }\n`
await writeFile(root+'/generated/model.circom',generated)
const run=(script,args)=>new Promise((yes,no)=>{
 const p=spawn(process.execPath,[script,...args],{cwd:root,stdio:'inherit'});p.on('error',no);p.on('exit',c=>c===0?yes():no(new Error(`Command exited ${c}`)))
})
const snark=resolve(root,'node_modules/snarkjs/build/cli.cjs')
await run(resolve(root,'node_modules/circom2/cli.js'),['circuits/zkml.circom','--r1cs','--wasm','--sym','--O2','--inspect','-o',out])
await run(snark,['r1cs','info',out+'/zkml.r1cs'])
// Optional existing development phase-2 powers, verified before use.
let ptau=process.env.ZKML_PTAU
if(!ptau){
 ptau=out+'/final.ptau'
 await run(snark,['powersoftau','new','bn128','15',out+'/initial.ptau'])
 await run(snark,['powersoftau','contribute',out+'/initial.ptau',out+'/contributed.ptau','--name=local-research','-e='+randomBytes(64).toString('hex')])
 await run(snark,['powersoftau','prepare','phase2',out+'/contributed.ptau',ptau])
}
ptau=resolve(ptau)
await run(snark,['powersoftau','verify',ptau])
await run(snark,['groth16','setup',out+'/zkml.r1cs',ptau,out+'/initial.zkey'])
await run(snark,['zkey','contribute',out+'/initial.zkey',out+'/zkml.zkey','--name=local-research','-e='+randomBytes(64).toString('hex')])
await run(snark,['zkey','verify',out+'/zkml.r1cs',ptau,out+'/zkml.zkey'])
await run(snark,['zkey','export','verificationkey',out+'/zkml.zkey',out+'/verification_key.json'])
const params={}
for(const n of [4,9])params[n]={C:constants.C[n-1],M:constants.M[n-1],partial:[56,57,56,60,60,63,64,63,60][n-1]}
await writeFile(pub+'/poseidon.json',JSON.stringify(params)+'\n')
await copyFile(root+'/node_modules/snarkjs/build/snarkjs.min.js',pub+'/snarkjs.min.js')
await copyFile(root+'/node_modules/snarkjs/COPYING',pub+'/SNARKJS-LICENSE.txt')
await copyFile(out+'/zkml_js/zkml.wasm',pub+'/zkml.wasm')
await copyFile(out+'/zkml.zkey',pub+'/zkml.zkey')
await copyFile(out+'/verification_key.json',pub+'/verification_key.json')
const files={}
for(const name of ['model.json','policy.json','poseidon.json','snarkjs.min.js','zkml.wasm','zkml.zkey','verification_key.json','runtime.mjs','worker.js']){
 const data=await readFile(pub+'/'+name);files[name]={sha256:hash(data),bytes:data.length}
}
const sourceFiles={}
for(const path of ['zk/circuits/zkml.circom','zk/generated/model.circom','client/public/zkml/runtime.mjs','client/public/zkml/worker.js'])sourceFiles[path]=hash(await readFile(resolve(root,'..',path)))
const manifest={format:'privface-zkml-artifacts-v1',circuit:'private-mlp-inference-match-v1',developmentOnly:true,
 modelTag:tagForHash(modelHash),policyTag:tagForHash(hash(policyBytes)),modelSHA256:modelHash,
 setupId:files['verification_key.json'].sha256,ptauSHA256:hash(await readFile(ptau)),
 r1csSHA256:hash(await readFile(out+'/zkml.r1cs')),sourceFiles,files,
 tooling:{circom2:'0.2.22',circomlib:'2.0.5',snarkjs:'0.7.6'},ceremony:'Single-party local research only; not production trusted setup'}
await writeFile(out+'/manifest.json',JSON.stringify(manifest,null,2)+'\n')
await writeFile(pub+'/manifest.json',JSON.stringify(manifest,null,2)+'\n')
console.log('M3 inference artifacts ready. Existing authentication is unchanged.')
